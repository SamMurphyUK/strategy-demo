/**
 * An emblem at one size as slots, `null` where it is clear. `flip` mirrors it left to right.
 * `turn` stands it on its side by swapping rows and columns, so the star-and-bars can run along a wing
 * that is drawn upright. Swapping keeps the light on the top left; flip after it to point the other way.
 */
export type EmblemBitmap = readonly (readonly (EmblemSlotKey | null)[])[];

export function emblemBitmap(emblem: Emblem, sizePx: number, flip = false, turn = false): EmblemBitmap {
  const drawn = emblem.sizes.find((item) => item.size === sizePx);
  if (!drawn) {
    throw new Error(`${emblem.name} is not drawn at ${sizePx} pixels.`);
  }
  const rows = turn ? Array.from({ length: drawn.width }, (_, column) => drawn.rows.map((text) => text[column] ?? ".").join("")) : drawn.rows;
  return rows.map((text) => {
    const cells = [...text].map((glyph) => {
      if (glyph === ".") {
        return null;
      }
      const slot = EMBLEM_GLYPH[glyph];
      if (!slot) {
        throw new Error(`${emblem.name} has the letter "${glyph}", which is not an emblem colour.`);
      }
      return slot;
    });
    return flip ? cells.reverse() : cells;
  });
}

export interface StampOptions {
  /** Only these cells take the emblem. Leave it out to stamp anywhere on the canvas. */
  onlyOn?: (x: number, y: number) => boolean;
}

export interface StampCell {
  x: number;
  y: number;
  slot: EmblemSlotKey;
}

/**
 * The cells a stamp would write, with the middle of the emblem on `centre`. Cells off the canvas, clear
 * cells of the emblem, and cells `onlyOn` refuses are left out. The preview and the stamp both use this.
 */
export function emblemCells(
  bitmap: EmblemBitmap,
  centre: { x: number; y: number },
  canvas: { width: number; height: number },
  options: StampOptions = {},
): StampCell[] {
  const height = bitmap.length;
  const left = centre.x - Math.floor((bitmap[0]?.length ?? 0) / 2);
  const top = centre.y - Math.floor(height / 2);
  const cells: StampCell[] = [];
  for (let row = 0; row < height; row += 1) {
    const y = top + row;
    if (y < 0 || y >= canvas.height) {
      continue;
    }
    const line = bitmap[row] ?? [];
    for (let column = 0; column < line.length; column += 1) {
      const slot = line[column];
      const x = left + column;
      if (slot == null || x < 0 || x >= canvas.width || (options.onlyOn && !options.onlyOn(x, y))) {
        continue;
      }
      cells.push({ x, y, slot });
    }
  }
  return cells;
}

/** The grid with the emblem written into it. Rows that do not change are shared with the old grid. */
export function stampEmblem(
  grid: SpriteFrameGrid,
  bitmap: EmblemBitmap,
  centre: { x: number; y: number },
  options: StampOptions = {},
): SpriteFrameGrid {
  const canvas = { width: grid[0]?.length ?? 0, height: grid.length };
  const cells = emblemCells(bitmap, centre, canvas, options);
  if (cells.length === 0) {
    return grid;
  }
  const next = grid.slice();
  const copied = new Set<number>();
  for (const { x, y, slot } of cells) {
    if (!copied.has(y)) {
      next[y] = (grid[y] ?? []).slice();
      copied.add(y);
    }
    (next[y] as (typeof slot | null)[])[x] = slot;
  }
  return next;
}

/** Whether any of the grids has ink at a cell: the outline of the sprite as it shows. */
export function silhouetteOf(grids: readonly (SpriteFrameGrid | undefined)[]): (x: number, y: number) => boolean {
  return (x, y) => grids.some((grid) => (grid?.[y]?.[x] ?? null) !== null);
}
