import type { EmblemSlotKey, RosterFactionId, SpriteFrameGrid } from "./skeletonSchema";

/**
 * National emblems for the Stamp tool: pure data and the stamping rule, no DOM.
 *
 * Every emblem is drawn by hand as a grid of letters, one grid for each size, and not scaled up from
 * a small one. The letters are the emblem slots (see EMBLEM_GLYPH). Those slots are fixed colours:
 * a country's mapping does not touch them, so a red star on a Soviet sprite and on a captured one
 * is the same red. Each grid has a one-pixel dark outline, light from the top left (red is lit on
 * its upper edges, white is shaded on its lower ones), and an odd width and height so the middle
 * pixel is the pointer.
 *
 * 13 to 31 pixels suit the 48-pixel blockouts and small parts of the large sprites. 41 and 55 are for the
 * large sprites only: a bomber's wing or a big hull.
 *
 * The roster has six countries. MINOR is a grab-bag of small powers with no single national marking,
 * so it has no emblem. Italy, France, China and the Commonwealth air forces are not on the roster.
 */

/** The letter for each emblem colour. layeredUnit.ts writes the same letters in its files. */
export const EMBLEM_GLYPH: Readonly<Record<string, EmblemSlotKey>> = {
  D: "emblem_dark",
  R: "emblem_red",
  H: "emblem_red_light",
  C: "emblem_white",
  O: "emblem_white_shade",
  L: "emblem_blue",
};

/** The same table the other way round: the letter each emblem colour is written with. */
export const EMBLEM_SLOT_GLYPH = Object.fromEntries(Object.entries(EMBLEM_GLYPH).map(([glyph, slot]) => [slot, glyph])) as Readonly<Record<EmblemSlotKey, string>>;

export type EmblemId = "ger_balkenkreuz" | "ussr_red_star" | "us_star_and_bars" | "uk_roundel_type_c" | "jap_hinomaru";

/** One drawn size. `size` is the height; an emblem wider than it is tall says so in `width`. */
export interface EmblemSize {
  size: number;
  label: string;
  width: number;
  height: number;
  /** One string a row. "." is clear. */
  rows: readonly string[];
}

export interface Emblem {
  id: EmblemId;
  faction: RosterFactionId;
  name: string;
  /** What it is and when it was worn. */
  basis: string;
  /** Smallest first. */
  sizes: readonly EmblemSize[];
}

/** Roster countries that have no emblem, and why: see the note at the top. */
export const UNSUPPORTED_FACTIONS: readonly RosterFactionId[] = ["MINOR"];

function size(height: number, label: string, rows: readonly string[]): EmblemSize {
  return { size: height, label, width: rows[0]?.length ?? 0, height: rows.length, rows };
}

