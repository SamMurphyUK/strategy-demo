// Scans web/public/AUDIO for .ogg clips and writes web/src/audio/audio_manifest.ts.
// Run: node --experimental-strip-types web/scripts/generate_audio_manifest.ts

import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const audioRoot = join(webRoot, "public", "AUDIO");
const outFile = join(webRoot, "src", "audio", "audio_manifest.ts");

/**
 * One clip per cue. Map interface cues are the radio-button click. Panel
 * buttons use ui_panel_flick so that click can be swapped on its own. Guns
 * are guns: the Browning for aircraft, the cannon shot for the heavy pieces.
 * The T-34 files are the engine and the elevation gear, so they are not gunshots.
 */
const RADIO = "vintage_radio_button_006";
const CANNON = "Automatic Cannon - MK44 - 03 - Single Shot with Report 03";
/** Short board-piece flick for panel buttons. Its own cue, so the soundboard can retarget it. */
const PANEL_FLICK = "Placing Pieces on the Board 2";
const SOUND_CUE_MAP = {
  token_pickup: [RADIO],
  waypoint_tick: [RADIO],
  token_drop: [RADIO],
  split_wheel_tick: [RADIO],
  battle_arrow_lock: [RADIO],
  ui_button_click: [RADIO],
  ui_panel_flick: [PANEL_FLICK],
  order_cancel: [RADIO],
  fire_infantry: ["M1928A1_Thompson_Submachine_Gun_.45cal_0.3m_to_side_ORTF_Burst_of_four_x_1"],
  fire_artillery: [CANNON],
  fire_armor: [CANNON],
  fire_aircraft: ["M1919A4_Browning_Machine_Gun_.30cal_on_turret_1m_left_blanks_Triple_shots_x_2"],
  fire_naval: [CANNON],
  hit_impact: ["Impacts/Impact 059"],
  unit_destroyed: ["Impacts/Impact_Boom_Distorted_02"],
  stinger_war_room: ["Walkie Talkie,Cobra MicroTalk,Radio Communication,End,Noise Squelch,Beep,Series"],
  stinger_frontline: ["M1919A4_Browning_Machine_Gun_.30cal_on_turret_300m_in_front_blanks_Triple_shots_x_2"],
} as const;

function walkOgg(dir: string): string[] {
  const found: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      found.push(...walkOgg(full));
      continue;
    }
    if (name.toLowerCase().endsWith(".ogg")) {
      const stem = relative(audioRoot, full).replace(/\\/g, "/").replace(/\.ogg$/i, "");
      found.push(stem);
    }
  }
  return found;
}

const files = walkOgg(audioRoot).sort((a, b) => a.localeCompare(b));
const available = new Set(files);

for (const [cue, names] of Object.entries(SOUND_CUE_MAP)) {
  if (names.length !== 1) {
    throw new Error(`${cue} needs exactly one file, has ${names.length}`);
  }
  for (const name of names) {
    if (!available.has(name)) {
      throw new Error(`${cue} points at a missing file: ${name}`);
    }
  }
}

const cueLines = Object.entries(SOUND_CUE_MAP)
  .map(([cue, names]) => `  ${cue}: ${JSON.stringify(names)},`)
  .join("\n");

const source = `// Generated by web/scripts/generate_audio_manifest.ts. Do not edit by hand.

export const ALL_AUDIO_FILES = ${JSON.stringify(files, null, 2)} as const;

export const SOUND_CUES = ${JSON.stringify(Object.keys(SOUND_CUE_MAP))} as const;

export type SoundCue = (typeof SOUND_CUES)[number];

export const SOUND_CUE_MAP: Record<SoundCue, readonly string[]> = {
${cueLines}
};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, source, "utf8");
console.log(`Wrote ${files.length} clips to ${outFile}`);
